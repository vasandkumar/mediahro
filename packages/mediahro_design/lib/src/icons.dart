/// Semantic icon names (docs/06 §4). Material Symbols on Android/Windows,
/// SF-Symbols-style Cupertino glyphs on Apple platforms.
enum KIcon {
  video,
  music,
  photos,
  search,
  settings,
  sources,
  play,
  pause,
  stop,
  next,
  previous,
  seekForward,
  seekBack,
  subtitles,
  audioTrack,
  cast,
  pip,
  fullscreen,
  more,
  folder,
  server,
  openFile,
  link,
  lock,
  info,
  favourite,
  share,
  delete;

  IconData resolve(PlatformFamily family) =>
      family == PlatformFamily.apple ? _apple[this]! : _material[this]!;
}

