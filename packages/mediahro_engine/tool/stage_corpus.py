"""Stage the generated corpus into the engine example app (device runs).

Copies manifest items up to --max-bytes each (plus the helper files the
suites load: subs.srt, subs.ass, ext_subs/) from test-media/generated into
example/assets/corpus/, and writes the filtered manifest into
example/integration_test/corpus_manifest.dart so the integration tests can
declare one test per file synchronously.

Usage: python packages/mediahro_engine/tool/stage_corpus.py [--max-bytes N]
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLUGIN = HERE.parent
ROOT = PLUGIN.parents[1]
SRC = ROOT / "test-media" / "generated"
DEST = PLUGIN / "example" / "assets" / "corpus"
MANIFEST_DART = PLUGIN / "example" / "integration_test" / "corpus_manifest.dart"
HELPERS = ["subs.srt", "subs.ass", "chapters.ffmeta", "vobsub.sub"]


def main(argv: list[str]) -> int:
    max_bytes = 4_000_000
    if "--max-bytes" in argv:
        max_bytes = int(argv[argv.index("--max-bytes") + 1])
    manifest = json.loads((SRC / "manifest.json").read_text(encoding="utf-8"))
    for child in DEST.iterdir() if DEST.exists() else []:
        if child.name == ".keep":
            continue
        if child.is_dir():
            shutil.rmtree(child)
        else:
            child.unlink()
    DEST.mkdir(parents=True, exist_ok=True)
    kept = []
    for item in manifest["items"]:
        f = SRC / item["file"]
        if f.is_dir():
            # Disc folders (VID-007) are copied whole.
            shutil.copytree(f, DEST / item["file"], dirs_exist_ok=True)
            kept.append(item)
            continue
        if not f.is_file() or f.stat().st_size > max_bytes:
            continue
        shutil.copy2(f, DEST / item["file"])
        kept.append(item)
    for name in HELPERS:
        if (SRC / name).is_file():
            shutil.copy2(SRC / name, DEST / name)
    if (SRC / "ext_subs").is_dir():
        shutil.copytree(SRC / "ext_subs", DEST / "ext_subs", dirs_exist_ok=True)
    # Asset folders declared in example/pubspec.yaml must exist even when
    # empty; .keep files are tracked by git and skipped by the test.
    for d in [DEST, *[p for p in DEST.rglob("*") if p.is_dir()]]:
        (d / ".keep").touch()
    staged = dict(manifest, items=kept)
    MANIFEST_DART.write_text(
        "// Generated by tool/stage_corpus.py; the committed copy is empty.\n"
        "const String corpusManifest = r'''\n"
        + json.dumps(staged, indent=1)
        + "\n''';\n",
        encoding="utf-8",
    )
    print(f"stage-corpus: {len(kept)} files -> {DEST}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
