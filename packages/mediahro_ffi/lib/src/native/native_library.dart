import 'dart:ffi';
import 'dart:io';

import 'package:meta/meta.dart';

/// Every native library Mediahro ships, as built by `mediahro-deps`
/// (docs/05 §10). The `linking` column there is authoritative: LGPL
/// libraries are always loaded dynamically from their own file.
enum NativeLibrary {
  mpv('mpv', licence: 'LGPL-2.1-or-later', dynamicOnly: true),
  vips('vips', licence: 'LGPL-2.1-or-later', dynamicOnly: true),
  jxl('jxl', licence: 'BSD-3-Clause'),
  avif('avif', licence: 'BSD-2-Clause'),
  raw('raw', licence: 'CDDL-1.0'),
  smb2('smb2', licence: 'LGPL-2.1-or-later', dynamicOnly: true),
  nfs('nfs', licence: 'LGPL-2.1-or-later', dynamicOnly: true),
  curl('curl', licence: 'curl'),
  archive('archive', licence: 'BSD-2-Clause'),
  ebur128('ebur128', licence: 'MIT'),
  chromaprint('chromaprint', licence: 'LGPL-2.1-or-later', dynamicOnly: true),
  openmpt('openmpt', licence: 'BSD-3-Clause'),
  whisper('whisper', licence: 'MIT'),
  uchardet('uchardet', licence: 'MPL-1.1');

  const NativeLibrary(
    this.baseName, {
    required this.licence,
    this.dynamicOnly = false,
  });

  /// Name without platform prefix/suffix, e.g. `mpv` → `libmpv.so`.
  final String baseName;

  /// SPDX identifier, mirrored in the SBOM.
  final String licence;

  /// True for LGPL libraries, which must never be statically linked (docs/09 §2).
  final bool dynamicOnly;
}

/// Platform file name for [lib] following the `mediahro-deps` archive layout.
@visibleForTesting
String nativeLibraryFileName(
  NativeLibrary lib, {
  required String os,
}) => switch (os) {
  'android' || 'linux' => 'lib${lib.baseName}.so',
  // Apple builds ship each library as a dynamic framework inside the bundle.
  'ios' || 'macos' => '${lib.baseName}.framework/${lib.baseName}',
  'windows' => '${lib.baseName}.dll',
  _ => throw UnsupportedError('Unsupported OS: $os'),
};

/// Thrown when a native library is missing, which is mapped to
/// "This feature needs a component that is missing from this build."
final class NativeLibraryUnavailable implements Exception {
  const NativeLibraryUnavailable(this.library, this.cause);

  final NativeLibrary library;
  final Object cause;

  @override
  String toString() => 'NativeLibraryUnavailable(${library.baseName}): $cause';
}

/// Loads and caches native libraries. Bindings generated by ffigen take the
/// returned [DynamicLibrary].
final class NativeLibraries {
  NativeLibraries._();

  static final Map<NativeLibrary, DynamicLibrary> _cache = {};

  static DynamicLibrary open(NativeLibrary lib) => _cache[lib] ??= _load(lib);

  /// Whether [lib] can be opened in this build (feature detection without throwing).
  static bool isAvailable(NativeLibrary lib) {
    try {
      open(lib);
      return true;
    } on NativeLibraryUnavailable {
      return false;
    }
  }

  static DynamicLibrary _load(NativeLibrary lib) {
    final name = nativeLibraryFileName(lib, os: Platform.operatingSystem);
    try {
      return DynamicLibrary.open(name);
      // DynamicLibrary.open reports a missing library only as ArgumentError.
      // ignore: avoid_catching_errors
    } on ArgumentError catch (e) {
      throw NativeLibraryUnavailable(lib, e);
    }
  }
}
